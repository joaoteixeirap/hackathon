// Official IBGE snapshot. Run pnpm catalog:sp to refresh the versioned catalogue.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
const localitiesURL = "https://servicodados.ibge.gov.br/api/v1/localidades/estados/35/municipios?orderBy=nome";
const geometryURL = "https://servicodados.ibge.gov.br/api/v3/malhas/estados/35?formato=application/vnd.geo%2Bjson&intrarregiao=municipio&qualidade=minima";
mkdirSync(".cache", { recursive: true });
mkdirSync("src/data", { recursive: true });
mkdirSync("public/data", { recursive: true });
async function snapshot(url, path) {
  if (existsSync(path) && !process.argv.includes("--refresh")) return JSON.parse(readFileSync(path, "utf8"));
  const r = await fetch(url, { signal: AbortSignal.timeout(60000) });
  if (!r.ok) throw new Error(`IBGE HTTP ${r.status}`);
  const data = await r.json(); writeFileSync(path, JSON.stringify(data)); return data;
}
const names = await snapshot(localitiesURL, ".cache/ibge-sp-municipalities.json");
const geo = await snapshot(geometryURL, ".cache/ibge-sp-geometry.json");
if (!Array.isArray(names) || names.length !== 645 || geo.features?.length !== 645) throw new Error("Unexpected IBGE catalogue; review before changing the snapshot.");
const geometries = new Map(geo.features.map(f => [String(f.properties.codarea), f.geometry]));
function bounds(geometry) {
  const pts = geometry.coordinates.flat(geometry.type === "MultiPolygon" ? 2 : 1);
  return [Math.min(...pts.map(p=>p[0])), Math.min(...pts.map(p=>p[1])), Math.max(...pts.map(p=>p[0])), Math.max(...pts.map(p=>p[1]))];
}
const slug = name => name.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const cities = names.map(m => {
  const geometry = geometries.get(String(m.id)); if (!geometry) throw new Error(`Geometry missing: ${m.id}`);
  const b = bounds(geometry);
  return { ibge_code: String(m.id), slug: slug(m.nome), name: m.nome, state: "SP", center_lat: +( (b[1]+b[3])/2).toFixed(5), center_lng: +( (b[0]+b[2])/2).toFixed(5), zoom: 11.5, bbox: b };
});
if(new Set(cities.map(c=>c.slug)).size!==645)throw new Error("Duplicate municipality slug");
const checked_on = new Date().toISOString().slice(0,10);
writeFileSync("src/data/sp-cities.json", JSON.stringify({ checked_on, source: "IBGE · Localidades e Malhas simplificadas", localities_url: localitiesURL, geometry_url: geometryURL, center_method: "midpoint of simplified municipal bounding box; approximate, not municipal seat", cities }, null, 2)+"\n");
writeFileSync("public/data/sp-municipalities.geojson", JSON.stringify(geo));
const quote = s => `'${s.replaceAll("'", "''")}'`;
const values = cities.map(c => `(${quote(`00000035-0000-4000-8000-${c.ibge_code.padStart(12,"0")}`)},${quote(c.slug)},${quote(c.name)},'SP',${c.center_lat},${c.center_lng},${c.zoom},array[${c.bbox.join(",")}],${quote(c.ibge_code)},${quote(checked_on)})`).join(",\n");
const upsert=`insert into cities(id,slug,name,state,center_lat,center_lng,zoom,bbox,ibge_code,catalog_checked_on) values\n${values}\non conflict(slug) do update set ibge_code=excluded.ibge_code,catalog_checked_on=excluded.catalog_checked_on;\n`;
const initialMigration="supabase/migrations/0021_sp_cities.sql";
if(!existsSync(initialMigration))writeFileSync(initialMigration,`-- IBGE snapshot ${checked_on}; generated by scripts/catalog-sp.mjs. Approximate map centres.\n-- Preserve existing IDs, centres and bbox (notably Santos); attach provenance.\nalter table cities add column ibge_code text unique, add column catalog_checked_on date;\n${upsert}`);
else{writeFileSync(".cache/sp-cities-upsert.sql",upsert);console.log("Existing migration preserved. Review .cache/sp-cities-upsert.sql in a NEW migration if the catalogue changed.");}
console.log(`Prepared ${cities.length} SP cities from IBGE; ${checked_on}. No database mutation.`);
